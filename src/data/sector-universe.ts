// ── Helper functions ──

// First-wins: stocks appearing in multiple sectors (e.g. NVDA in Semiconductors AND
// Technology) map to their first (most specific) sector for classification purposes.
const _symbolToSector = new Map<string, SectorDefinition>();
for (const sector of SECTOR_UNIVERSE) {
  for (const stock of sector.stocks) {
    if (!_symbolToSector.has(stock.symbol)) {
      _symbolToSector.set(stock.symbol, sector);
    }
  }
}

export function getSectorForSymbol(symbol: string): string {
  return _symbolToSector.get(symbol)?.displayName ?? "Other";
}

export function getSectorETFForSymbol(symbol: string): string | null {
  return _symbolToSector.get(symbol)?.etf ?? null;
}

export function getAllSectorSymbols(): string[] {
  return [...new Set(SECTOR_UNIVERSE.flatMap((s) => s.stocks.map((st) => st.symbol)))].sort();
}

export function getSectorDefinitions(): SectorDefinition[] {
  return SECTOR_UNIVERSE;
}

/** Get the 14 original GICS equity sectors. */
export function getEquitySectors(): SectorDefinition[] {
  return SECTOR_UNIVERSE.filter((s) => s.category === "gics_sector");
}

/** Get sub-sector leading indicators (KRE, XHB, XRT, IYT, ITA, ARKX, UFO, AIQ). */
export function getSubSectors(): SectorDefinition[] {
  return SECTOR_UNIVERSE.filter((s) => s.category === "sub_sector");
}

/** Get cross-asset ETFs (GLD, TLT, HYG, EEM, UUP). */
export function getCrossAssetETFs(): SectorDefinition[] {
  return SECTOR_UNIVERSE.filter((s) => s.category === "cross_asset");
}

/** Get leadership basket ETFs (MAGS, QQQ, IWM, ARKK). */
export function getLeadershipBaskets(): SectorDefinition[] {
  return SECTOR_UNIVERSE.filter((s) => s.category === "leadership_basket");
}

/** Get all sectors that have stocks for enrichment (excludes cross-asset ETFs). */
export function getSectorsWithStocks(): SectorDefinition[] {
  return SECTOR_UNIVERSE.filter((s) => s.stocks.length > 0);
}
